interface StoryFrame {
  headline?: string;
  line?: string;
  text?: string;
}

/**
 * Builds the frame strings the renderer prints.
 *
 * `splitCopy` in render.ts reads the first line as the headline and the rest as
 * the deck, so each frame is joined as "headline\nline". Anything the model
 * returned that is not copy has already been dropped by `cleanCopy`.
 */
function parseStoryFrames(
  aiResult: string | null,
  frameCount: number,
  role: { name: string; tagline: string } | null,
  theme: string
): { frames: string[]; caption: string; accentColor?: string } {
  const fallbackCaption = role
    ? `${theme || "a"} story featuring ${role.name.toLowerCase()}`
    : theme
      ? `${theme} story`
      : "the resistance night";

  if (aiResult) {
    const parsed = extractJson<{ frames?: StoryFrame[]; caption?: string; accent?: unknown }>(aiResult);

    if (parsed?.frames?.length) {
      const frames = parsed.frames
        .map((f) => {
          const headline = cleanCopy(f.headline || f.text || "");
          const line = cleanCopy(f.line || "");
          return [headline, line].filter(Boolean).join("\n");
        })
        .filter(Boolean)
        .slice(0, frameCount);

      if (frames.length) {
        return {
          frames,
          caption: cleanCopy(parsed.caption || "") || fallbackCaption,
          accentColor: validateAccent(parsed.accent) || undefined,
        };
      }
    }

    // The model answered with prose. Salvage it rather than dropping to
    // templates, but strip the scaffolding first.
    const prose = splitFrames(aiResult, frameCount);

    if (prose.length) {
      return { frames: prose, caption: fallbackCaption };
    }
  }

  const defaults = role
    ? [
        `which role are you tonight?\nmerlin sees everything. the assassin sees merlin.`,
        `${role.name.toLowerCase()}\n${role.tagline.toLowerCase()}`,
        `someone at this table is lying\nand they are very good at it.`,
        `the resistance night\ntime to lie to your friends.`,
        `five to ten players\none traitor. one night.`,
      ]
    : [
        `someone at this table is lying\nand they are very good at it.`,
        `the resistance night\ntime to lie to your friends.`,
        `five to ten players\none traitor. one night.`,
        `no accounts. no data.\njust you, your friends, and a phone full of secrets.`,
        `tonight, everyone is a suspect.`,
      ];

  return { frames: defaults.slice(0, frameCount), caption: fallbackCaption };
}

/** Frames beyond this are dropped by the renderer, so nothing asks for more. */
export const MAX_STORY_FRAMES = 5;

/**
 * Generates, checks, and retries once before settling - the same discipline
 * generateContent in ai.ts applies to posts, reels and carousels. Stories
 * used to be generated by an entirely separate path with none of it: no mode,
 * no "no role" support, no quality gate, no role-name guardrail, so freedom
 * mode's fixes for the other three types never reached stories at all.
 */
export async function generateStories(
  steer?: string,
  count?: number,
  theme?: string,
  roleId?: string,
  mode: GenerationMode = "template"
): Promise<ContentItem[]> {
  let lastProblems = "";
  let lastItems: ContentItem[] | null = null;

  const forbidRoleNames = mode === "free" && !(roleId || "").trim();

  // Resolved once and held fixed across every retry attempt - see the same
  // fix in ai.ts's generateContent. Re-resolving inside generateStoriesOnce
  // on every attempt meant template mode's random theme/role pick could
  // change between attempts, and made a stable expectedRole/expectedCount
  // impossible to check here.
  const { theme: selectedTheme, role: selectedRole } = resolveGenerationInputs(mode, theme, roleId);
  const frameCount = count
    ? Math.max(1, Math.min(MAX_STORY_FRAMES, Math.round(count)))
    : requestedCount(steer, 4, MAX_STORY_FRAMES);

  const expectedRole = selectedRole?.name;
  const expectedCount = frameCount;

  for (let attempt = 0; attempt < 3; attempt++) {
    const note = lastProblems
      ? `${steer || ""}\n\nYour previous attempt was rejected: ${lastProblems}. Fix exactly that.`.trim()
      : steer;

    const items = await generateStoriesOnce(note, selectedTheme, selectedRole, roleId, frameCount, mode);
    const verdict = assessContent(items[0], { steer, forbidRoleNames, expectedRole, expectedCount });
    if (verdict.ok) return items;

    lastItems = items;
    lastProblems = describeProblems(verdict.problems);
    console.warn(`story did not clear quality (attempt ${attempt + 1}): ${lastProblems}`);
  }

  console.warn(`Shipping story unresolved after 3 attempts: ${lastProblems}`);
  return lastItems!;
}

async function generateStoriesOnce(
  steer: string | undefined,
  selectedTheme: string,
  role: ReturnType<typeof resolveGenerationInputs>["role"],
  roleId: string | undefined,
  frameCount: number,
  mode: GenerationMode
): Promise<ContentItem[]> {
  await loadHistory();

  const variant = pickDesignVariant();

  const themeLine = selectedTheme ? `Theme: ${selectedTheme}\n` : "";
  const roleLine = role ? `Featured Role: ${role.name}, ${role.tagline}\n` : "";
  const roleGuidance = mode === "free" && !role ? `\n${noRoleGuidance()}\n` : "";

  const intro =
    mode === "free"
      ? `Write the on-screen copy for a ${frameCount}-frame Instagram Story about "The Resistance Night," a social deduction party game where 5 to 10 friends lie, bluff and betray each other, pass and play on one phone. Pick one concrete angle and commit to it, the sharpest story you can write for this game.`
      : `Write the on-screen copy for a ${frameCount}-frame Instagram Story for "The Resistance Night," a social deduction party game.`;

  const prompt = `${intro}

${themeLine}${roleLine}${buildHistoryContext()}
${roleGuidance}
You are writing the words that get printed on the image. Nothing else.

Return JSON in exactly this shape:
{"frames":[{"headline":"...","line":"..."}],"caption":"...","accent":"#rrggbb"}

- Produce exactly ${frameCount} ${frameCount === 1 ? "frame" : "frames"}.
- "headline" is 2 to 6 words, the big line on the frame.
- "line" is one short supporting sentence, or "" if the headline stands alone.
- "caption" is one sentence describing the story for the dashboard.
- "accent" is a #rrggbb colour that suits this story, readable on a near-black background. Stay in the brand world: gold #c89858, champagne #f4e8c8, ruby #c8324a, emerald #3fb083, steel #8a92b8, or a considered variation.
${COPY_RULES}`;

  const aiResult = await callAI(withSteer(prompt, steer));
  const { frames, caption, accentColor } = parseStoryFrames(aiResult, frameCount, role, selectedTheme);

  recordContentUsage({
    theme: selectedTheme,
    roleId: role?.id || roleId || "",
    type: "story",
    hook: frames[0]?.slice(0, 80) || "",
    designVariant: variant.id,
  });

  const subject = [role?.name, selectedTheme].filter(Boolean).join(", ") || "the resistance night";

  return [{
    id: generateId(),
    type: "story" as ContentType,
    title: `Story: ${subject}`,
    caption,
    hashtags: getHashtags(10),
    storyFrames: frames,
    accentColor,
    generationMode: mode,
    status: "pending",
    createdAt: new Date().toISOString(),
    theme: selectedTheme,
    agentId: "story-generator",
  }];
}

