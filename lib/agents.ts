export interface CalendarDay {
  day: string;
  type: ContentType;
  theme: string;
  role: string;
  designVariant: string;
  notes: string;
}

export async function generateContentCalendar(steer?: string): Promise<ContentItem> {
  await loadHistory();
  const daysOfWeek = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"];
  const contentTypes: ContentType[] = ["reel", "post", "carousel", "story"];

  const prompt = `You are a content strategist for "The Resistance Night," an indie social deduction party game.

Create a 7-day Instagram content calendar for this week. For each day, assign:
1. Content type (reel, post, carousel, or story)
2. Theme from: deception & trust, medieval mystery, party night vibes, role reveal drama, friendship chaos, strategy & bluffing, dark castle aesthetic, good vs evil, game night essentials, social deduction tips
3. Featured role from: Merlin, Assassin, Percival, Morgana, Mordred, Oberon, The Lovers
4. Brief content notes (1-2 sentences describing the post concept)

Rules:
- No two consecutive days should use the same content type
- Each role should appear at most once
- Balance themes across the week (no repeats)
- Friday/Saturday should be high-engagement formats (reels or carousels)
- Sunday is lighter, community-focused content
${buildHistoryContext()}

Format as a clean day-by-day plan.`;

  const aiResult = await callAI(withSteer(prompt, steer));

  const usedThemes = new Set<string>();
  const usedRoles = new Set<string>();
  let lastType: ContentType | null = null;

  const calendar: CalendarDay[] = daysOfWeek.map((day, i) => {
    let type = contentTypes[i % contentTypes.length];
    if (type === lastType) type = contentTypes[(i + 1) % contentTypes.length];
    lastType = type;

    let theme: string;
    do { theme = pickRandomTheme(); } while (usedThemes.has(theme) && usedThemes.size < 10);
    usedThemes.add(theme);

    let role = pickRandomRole();
    let attempts = 0;
    while (usedRoles.has(role.name) && attempts < 7) { role = pickRandomRole(); attempts++; }
    usedRoles.add(role.name);

    const variant = pickDesignVariant();

    return {
      day,
      type,
      theme,
      role: role.name,
      designVariant: variant.id,
      notes: `${role.name} + ${theme}. Visual: ${variant.motif}.`,
    };
  });

  const calendarText = aiResult || calendar.map((d) =>
    `${d.day.toUpperCase()}\nType: ${d.type} | Theme: ${d.theme} | Role: ${d.role}\n${d.notes}`
  ).join("\n\n");

  return {
    id: generateId(),
    type: "post" as ContentType,
    title: `Content Calendar: Week of ${new Date().toLocaleDateString("en-US", { month: "short", day: "numeric" })}`,
    caption: calendarText,
    hashtags: ["#contentcalendar"],
    status: "pending",
    createdAt: new Date().toISOString(),
    theme: "content calendar",
    agentId: "content-calendar",
  };
}

