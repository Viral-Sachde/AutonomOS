export async function generateIllustrations(steer?: string): Promise<ContentItem[]> {
  await loadHistory();
  const recentCategories = buildHistoryContext().match(/illustration-(\w+)/g)?.map(s => s.replace("illustration-", "")) || [];
  const availableCategories = illustrationCategories.filter(c => !recentCategories.includes(c));
  const targetCategories = availableCategories.length >= 3
    ? availableCategories.sort(() => Math.random() - 0.5).slice(0, 3)
    : illustrationCategories.sort(() => Math.random() - 0.5).slice(0, 3);

  const role = pickRandomRole();
  const theme = pickRandomTheme();
  const variant = pickDesignVariant();

  const prompt = `You are an SVG illustrator creating assets for "The Resistance Night," a medieval social deduction party game.

STRICT PALETTE (use ONLY these hex values):
- Background: ${P.bg} (ink-black)
- Paper: ${P.paper} (deep indigo)
- Gold: ${P.gold} (warm gold, primary accent)
- Cream: ${P.cream} (light text/highlights)
- Ruby: ${P.ruby} (evil/danger/dramatic)
- Emerald: ${P.emerald} (good/success)
- Steel: ${P.steel} (secondary text)
- Deep: ${P.deep} (darkest layer)

STYLE GUIDE:
- Riso-print registration offsets (duplicate shapes shifted 4px with 50% opacity)
- Arch-shaped portrait frames with 2px stroke borders
- Flat geometric shapes, no gradients except opacity
- Star sigils as decorative elements (8-point stars)
- Castle silhouettes, crescent moons, medieval motifs
- Clean SVG with viewBox, no embedded images

Featured role: ${role.name}, ${role.tagline}
Theme: ${theme}
Visual direction: ${variant.motif}

Generate 3 SVG illustrations, one for each category: ${targetCategories.join(", ")}

For each, return the complete SVG code between <svg> tags. Keep each under 2KB.
Label each with its category.${buildHistoryContext()}`;

  const aiResult = await callAI(withSteer(prompt, steer));

  if (aiResult) {
    const svgMatches = [...aiResult.matchAll(/<svg[\s\S]*?<\/svg>/gi)];
    if (svgMatches.length > 0) {
      return svgMatches.slice(0, 3).map((match, i) => {
        const category = targetCategories[i] || "scene";
        const svgCode = match[0];

        recordContentUsage({
          theme,
          roleId: role.id,
          type: "post",
          hook: `illustration-${category}`,
          designVariant: variant.id,
        });

        return {
          id: generateId(),
          type: "post" as ContentType,
          title: `Illustration: ${category}, ${role.name}`,
          caption: `${category} illustration in the compline palette featuring ${theme} theme. ready for posts, stories, and marketing assets.`,
          hashtags: getHashtags(8),
          svgCode,
          illustrationCategory: category,
          status: "pending" as const,
          createdAt: new Date().toISOString(),
          theme,
          agentId: "illustration-studio",
        };
      });
    }
  }

  const usedNames = new Set(
    buildHistoryContext().match(/"([^"]+)"/g)?.map(s => s.slice(1, -1)) || []
  );
  const available = illustrationTemplates.filter(t =>
    targetCategories.includes(t.category) && !usedNames.has(t.name)
  );
  const picks = available.length >= 3
    ? available.sort(() => Math.random() - 0.5).slice(0, 3)
    : illustrationTemplates
        .filter(t => targetCategories.includes(t.category))
        .sort(() => Math.random() - 0.5)
        .slice(0, 3);

  return picks.map((template) => {
    recordContentUsage({
      theme,
      roleId: role.id,
      type: "post",
      hook: `illustration-${template.category}: ${template.name}`,
      designVariant: variant.id,
    });

    return {
      id: generateId(),
      type: "post" as ContentType,
      title: `Illustration: ${template.name}`,
      caption: `${template.category} illustration: "${template.name}". compline palette, ${theme} theme. use in posts, stories, headers, or as standalone art.`,
      hashtags: getHashtags(8),
      svgCode: template.svg,
      illustrationCategory: template.category,
      status: "pending" as const,
      createdAt: new Date().toISOString(),
      theme,
      agentId: "illustration-studio",
    };
  });
}
